// 받침 맞춰 조사 붙이기
const PAIRS = { 이: ["이", "가"], 은: ["은", "는"], 을: ["을", "를"], 와: ["과", "와"], 랑: ["이랑", "랑"], 의: ["의", "의"], 에게: ["에게", "에게"], 도: ["도", "도"], 에게는: ["에게는", "에게는"] };
function hasB(w) {
  const c = String(w).charCodeAt(String(w).length - 1);
  return c >= 0xac00 && c <= 0xd7a3 ? (c - 0xac00) % 28 !== 0 : false;
}
export function fill(line, X, Y) {
  return line.replace(/\{([XY])(?::([^}]+))?\}/g, (_, who, p) => {
    const w = who === "X" ? X : Y;
    if (!p) return w;
    const pr = PAIRS[p] || [p, p];
    return w + (hasB(w) ? pr[0] : pr[1]);
  });
}
