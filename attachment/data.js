// 50 초과면 높음
export function typeOf(anx, avo) {
  const hA = anx > 50;
  const hV = avo > 50;
  if (!hA && !hV) return TYPES.secure;
  if (hA && !hV) return TYPES.anxious;
  if (!hA && hV) return TYPES.avoidant;
  return TYPES.fearful;
}

