export const topicOf = (key) => TOPICS.find((t) => t.key === key) || null;

// 라이어 수: 6명부터 두 명까지(5명 이하에서 두 명이면 라이어가 너무 쉽게 이김)
export const maxLiars = (n) => (n >= 6 ? 2 : 1);

/* 판 번호: 헷갈리는 글자(0·O·1·I·L) 뺀 5글자 */
const ABC = "23456789ABCDEFGHJKMNPQRSTUVWXYZ";
export function newCode(rand = Math.random) {
  let s = "";
  for (let i = 0; i < 5; i++) s += ABC[Math.floor(rand() * ABC.length)];
  return s;
}
export const validCode = (k) => typeof k === "string" && /^[2-9A-HJKMNP-Z]{5}$/.test(k);

/* 판 설정: { n 인원, t 주제 키(또는 any), l 라이어 수, s 스파이(0/1), k 판 번호, r 몇 번째 판 } */
export function cfgOK(c) {
  return !!c && Number.isInteger(c.n) && c.n >= MIN_N && c.n <= MAX_N
    && (c.t === ANY || !!topicOf(c.t))
    && Number.isInteger(c.l) && c.l >= 1 && c.l <= maxLiars(c.n)
    && (c.s === 0 || c.s === 1)
    && validCode(c.k)
    && Number.isInteger(c.r) && c.r >= 1 && c.r <= 999;
}
export function cfgFromParams(get) {
  const c = { n: +get("n"), t: String(get("t") || ""), l: +get("l"), s: +get("s") || 0, k: String(get("k") || "").toUpperCase(), r: +(get("r") || 1) };
  return cfgOK(c) ? c : null;
}
export const queryOf = (c) => `?n=${c.n}&t=${c.t}&l=${c.l}&s=${c.s}&k=${c.k}${c.r > 1 ? `&r=${c.r}` : ""}`;
export const seedOf = (c) => `liar:v1:${c.n}:${c.t}:${c.l}:${c.s}:${c.k}:${c.r}`;

/* 한 판 나누기 — 결과는 판 설정만으로 정해진다(같은 설정이면 언제 어디서 열어도 같음)
 * 돌려주는 것: topic(주제), word(시민 제시어), liarWord(스파이 모드에서 라이어가 받는 말, 아니면 null),
 *             liars(라이어 번호, 작은 순), roles[번호-1] = { no, liar, word(그 사람 화면에 뜨는 말, 일반 라이어는 null) },
 *             order(설명하는 차례: 번호 순열) */
export function deal(c) {
  if (!cfgOK(c)) return null;
  const rand = seededRandom(seedOf(c));
  const topic = c.t === ANY ? TOPICS[Math.floor(rand() * TOPICS.length)] : topicOf(c.t);
  let word, liarWord = null;
  if (c.s) {
    const [a, b] = topic.pairs[Math.floor(rand() * topic.pairs.length)].split("|");
    [word, liarWord] = rand() < 0.5 ? [a, b] : [b, a];
  } else {
    word = topic.words[Math.floor(rand() * topic.words.length)];
  }
  const nums = Array.from({ length: c.n }, (_, i) => i + 1);
  const liars = shuffle(nums, rand).slice(0, c.l).sort((x, y) => x - y);
  const roles = nums.map((no) => {
    const liar = liars.includes(no);
    return { no, liar, word: liar ? liarWord : word };
  });
  const order = shuffle(nums, rand);
  return { topic: { key: topic.key, name: topic.name }, word, liarWord, liars, roles, order };
}
export const cardFor = (c, no) => deal(c)?.roles[no - 1] || null;

