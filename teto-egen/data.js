// 친선 경기(친구 비교) 한 줄
export function pairNote(a, b) {
  if (a.id === b.id) return "같은 팀이에요. 서로 설명 안 해도 통하는 게 많아요.";
  if (a.side === b.side) return "같은 편인데 세기가 달라요. 한 사람이 끌면 다른 사람이 속도를 맞춰 줘요.";
  if (a.match === b.id || b.match === a.id) return "반대편 끝에서 줄을 당기는 사이예요. 서로 없는 걸 채워 주는 조합이에요.";
  return "반대편에서 당기는 사이예요. 결정은 테토 쪽이, 분위기는 에겐 쪽이 맡으면 편해요.";
}
